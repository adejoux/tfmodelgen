package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestRunGeneratesFile(t *testing.T) {
	dir := t.TempDir()
	var stdout, stderr bytes.Buffer
	code := run([]string{
		"-spec", "testdata/openapi.json", "-path", "/projects/{id}",
		"-package", "provider", "-out", dir, "-attrs", "status",
	}, &stdout, &stderr)
	if code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	b, err := os.ReadFile(filepath.Join(dir, "project_model_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(b, []byte("// Code generated by tfmodelgen")) || !bytes.Contains(b, []byte("package provider")) {
		t.Fatalf("unexpected output:\n%.300s", b)
	}
	if !strings.Contains(stderr.String(), "warning:") {
		t.Fatal("warnings not reported")
	}
	if !bytes.Contains(b, []byte("ProjectDataSourceSchema()")) || bytes.Contains(b, []byte("rsschema")) {
		t.Fatal("data source schema expected by default, and only it")
	}
}

func TestRunListsOperations(t *testing.T) {
	var stdout, stderr bytes.Buffer
	if code := run([]string{"-spec", "testdata/openapi.json"}, &stdout, &stderr); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	if !strings.Contains(stdout.String(), "GET /projects/{id}  (getProject)") {
		t.Fatalf("listing: %s", stdout.String())
	}
}

func TestRunErrors(t *testing.T) {
	for _, args := range [][]string{
		{},
		{"-spec", "missing.json"},
		{"-spec", "testdata/openapi.json", "-path", "/nope"},
		{"-spec", "testdata/openapi.json", "-path", "/projects", "-schema", "bogus"},
	} {
		var stdout, stderr bytes.Buffer
		if code := run(args, &stdout, &stderr); code == 0 {
			t.Errorf("%v: exit 0", args)
		}
	}
}
