package prior

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"github.com/adejoux/tfmodelgen/internal/gen"
)

// Number types: the schema JSON only knows "number", so the type of the
// model field is chosen when generating.
const (
	NumberNumber  = "number"  // types.Number, exact (math/big)
	NumberInt64   = "int64"   // types.Int64
	NumberFloat64 = "float64" // types.Float64
)

// Options configures Generate.
type Options struct {
	Package string
	Name    string // Go base name, default derived from the resource type
	Source  string // shown in the generated header
	// Number is the default type of number attributes, NumberNumber when
	// empty. Types overrides it by attribute path: "size",
	// "settings.max_items" (collection elements are not part of the path).
	Number string
	Types  map[string]string
}

const (
	fwAttr     = "github.com/hashicorp/terraform-plugin-framework/attr"
	fwDiag     = "github.com/hashicorp/terraform-plugin-framework/diag"
	fwResource = "github.com/hashicorp/terraform-plugin-framework/resource"
	fwRSSchema = "github.com/hashicorp/terraform-plugin-framework/resource/schema"
	fwTypes    = "github.com/hashicorp/terraform-plugin-framework/types"
)

// DefaultName returns the Go base name of a resource type, without its
// provider prefix: monprov_ma_resource -> MaResource.
func DefaultName(r Resource) string {
	typ := r.Type
	if p := providerName(r.Provider); p != "" && strings.HasPrefix(typ, p+"_") {
		typ = strings.TrimPrefix(typ, p+"_")
	}
	return gen.GoName(typ)
}

// FileName returns the default name of the generated file.
func FileName(name string, version int64) string {
	return fmt.Sprintf("%s_schema_v%d_gen.go", gen.FileName(name), version)
}

type structDef struct {
	name, doc string
	fields    []string
}

type generator struct {
	o        Options
	suffix   string
	structs  []*structDef
	names    map[string]bool
	used     map[string]bool // Types entries consumed
	imports  map[string]bool
	needAttr bool
}

// Generate renders the Go file holding, for the schema version of r:
// <Name>SchemaV<n>() returning the frozen schema, <Name>ModelV<n> and its
// nested models decoding a state stored with it, and
// <Name>StateUpgraderV<n>, a resource.StateUpgrader converting it with a
// function of the provider.
func Generate(r Resource, o Options) ([]byte, error) {
	if r.Schema == nil || r.Schema.Block == nil {
		return nil, fmt.Errorf("empty schema")
	}
	if o.Package == "" {
		o.Package = "provider"
	}
	if o.Name == "" {
		if r.Type == "" {
			return nil, fmt.Errorf("a name is required for a schema without resource type")
		}
		o.Name = DefaultName(r)
	}
	if err := checkNumber(o.Number); err != nil {
		return nil, err
	}
	for p, k := range o.Types {
		if err := checkNumber(k); err != nil {
			return nil, fmt.Errorf("%s: %w", p, err)
		}
	}
	g := &generator{
		o:       o,
		suffix:  fmt.Sprintf("V%d", r.Schema.Version),
		names:   map[string]bool{},
		used:    map[string]bool{},
		imports: map[string]bool{"context": true, fwDiag: true, fwResource: true, fwRSSchema: true},
	}
	root, attrs, blocks, err := g.object(r.Schema.Block.Attributes, r.Schema.Block.BlockTypes, "", o.Name)
	if err != nil {
		return nil, err
	}
	var unused []string
	for p := range o.Types {
		if !g.used[p] {
			unused = append(unused, p)
		}
	}
	if len(unused) > 0 {
		sort.Strings(unused)
		return nil, fmt.Errorf("no number attribute at %s", strings.Join(unused, ", "))
	}
	if g.needAttr {
		g.imports[fwAttr] = true
	}

	var b bytes.Buffer
	what := "schema version " + strconv.FormatInt(r.Schema.Version, 10)
	if r.Type != "" {
		what = r.Type + ", " + what
	}
	source := ""
	if o.Source != "" {
		source = " from " + o.Source
	}
	fmt.Fprintf(&b, "// Code generated by tfmodelgen prior%s (%s). DO NOT EDIT.\n\n", source, what)
	fmt.Fprintf(&b, "package %s\n\n", o.Package)
	b.WriteString(g.importBlock())

	schemaFn := o.Name + "Schema" + g.suffix
	upgrader := o.Name + "StateUpgrader" + g.suffix
	fmt.Fprintf(&b, "// %s returns the schema of version %d, frozen: it describes the\n", schemaFn, r.Schema.Version)
	fmt.Fprintf(&b, "// states stored by the releases that used it, whatever the current schema.\n")
	fmt.Fprintf(&b, "func %s() rsschema.Schema {\n\treturn rsschema.Schema{\n\t\tVersion: %d,\n", schemaFn, r.Schema.Version)
	if attrs != "" {
		fmt.Fprintf(&b, "\t\tAttributes: %s,\n", attrs)
	}
	if blocks != "" {
		fmt.Fprintf(&b, "\t\tBlocks: %s,\n", blocks)
	}
	b.WriteString("\t}\n}\n\n")

	for _, s := range g.structs {
		fmt.Fprintf(&b, "// %s\ntype %s struct {\n", s.doc, s.name)
		for _, f := range s.fields {
			b.WriteString("\t" + f + "\n")
		}
		b.WriteString("}\n\n")
	}

	fmt.Fprintf(&b, `// %[1]s returns the StateUpgrader of the states stored with
// schema version %[2]d: it decodes the prior state into %[3]s, calls
// convert and stores the value it returns, a model of the current schema.
//
//	func (r *myResource) UpgradeState(context.Context) map[int64]resource.StateUpgrader {
//		return map[int64]resource.StateUpgrader{
//			%[2]d: %[1]s(func(ctx context.Context, prior %[3]s) (myResourceModel, diag.Diagnostics) {
//				// copy, convert, and set the new attributes to null
//			}),
//		}
//	}
func %[1]s[T any](convert func(ctx context.Context, prior %[3]s) (T, diag.Diagnostics)) resource.StateUpgrader {
	s := %[4]s()
	return resource.StateUpgrader{
		PriorSchema: &s,
		StateUpgrader: func(ctx context.Context, req resource.UpgradeStateRequest, resp *resource.UpgradeStateResponse) {
			var prior %[3]s
			resp.Diagnostics.Append(req.State.Get(ctx, &prior)...)
			if resp.Diagnostics.HasError() {
				return
			}
			current, diags := convert(ctx, prior)
			resp.Diagnostics.Append(diags...)
			if resp.Diagnostics.HasError() {
				return
			}
			resp.Diagnostics.Append(resp.State.Set(ctx, current)...)
		},
	}
}
`, upgrader, r.Schema.Version, root, schemaFn)

	out, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("formatting generated code: %w", err)
	}
	return out, nil
}

func checkNumber(k string) error {
	switch k {
	case "", NumberNumber, NumberInt64, NumberFloat64:
		return nil
	}
	return fmt.Errorf("unknown number type %q (number, int64 or float64)", k)
}

func (g *generator) importBlock() string {
	var std, ext []string
	for path := range g.imports {
		line := strconv.Quote(path)
		if path == fwRSSchema {
			line = "rsschema " + line
		}
		if strings.Contains(path, ".") {
			ext = append(ext, line)
		} else {
			std = append(std, line)
		}
	}
	sort.Strings(std)
	sort.Strings(ext)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, l := range std {
		b.WriteString("\t" + l + "\n")
	}
	if len(std) > 0 && len(ext) > 0 {
		b.WriteString("\n")
	}
	for _, l := range ext {
		b.WriteString("\t" + l + "\n")
	}
	b.WriteString(")\n\n")
	return b.String()
}

// newStruct reserves a model name: <base>Model<suffix>.
func (g *generator) newStruct(base, path string) *structDef {
	name := base + "Model" + g.suffix
	for i := 2; g.names[name]; i++ {
		name = fmt.Sprintf("%sModel%d%s", base, i, g.suffix)
	}
	g.names[name] = true
	doc := name + " decodes a state stored with schema " + g.suffix + "."
	if path != "" {
		doc = name + " decodes " + path + " in a state stored with schema " + g.suffix + "."
	}
	s := &structDef{name: name, doc: doc}
	g.structs = append(g.structs, s)
	return s
}

func join(path, name string) string {
	if path == "" {
		return name
	}
	return path + "." + name
}

// object generates the model of a block or of a nested attribute object and
// returns its name and the Go expressions of its attributes and blocks maps
// (empty when there are none).
func (g *generator) object(attributes map[string]*Attribute, blocks map[string]*NestedBlock, path, base string) (name, attrs, blks string, err error) {
	s := g.newStruct(base, path)
	fieldNames := map[string]bool{}
	field := func(tf, goType string) {
		n := gen.GoName(tf)
		for i := 2; fieldNames[n]; i++ {
			n = fmt.Sprintf("%s%d", gen.GoName(tf), i)
		}
		fieldNames[n] = true
		s.fields = append(s.fields, fmt.Sprintf("%s %s `tfsdk:%q`", n, goType, tf))
	}

	var a strings.Builder
	for _, k := range sortedKeys(attributes) {
		goType, expr, err := g.attribute(attributes[k], join(path, k), base+gen.GoName(k))
		if err != nil {
			return "", "", "", fmt.Errorf("%s: %w", join(path, k), err)
		}
		field(k, goType)
		fmt.Fprintf(&a, "%q: %s,\n", k, expr)
	}
	var bl strings.Builder
	for _, k := range sortedKeys(blocks) {
		goType, expr, err := g.block(blocks[k], join(path, k), base+gen.GoName(k))
		if err != nil {
			return "", "", "", fmt.Errorf("%s: %w", join(path, k), err)
		}
		field(k, goType)
		fmt.Fprintf(&bl, "%q: %s,\n", k, expr)
	}
	if a.Len() > 0 {
		attrs = "map[string]rsschema.Attribute{\n" + a.String() + "}"
	}
	if bl.Len() > 0 {
		blks = "map[string]rsschema.Block{\n" + bl.String() + "}"
	}
	return s.name, attrs, blks, nil
}

func flags(a *Attribute) string {
	var f []string
	if a.Required {
		f = append(f, "Required: true")
	}
	if a.Optional || (!a.Required && !a.Computed) {
		f = append(f, "Optional: true")
	}
	if a.Computed {
		f = append(f, "Computed: true")
	}
	if a.Sensitive {
		f = append(f, "Sensitive: true")
	}
	if a.WriteOnly {
		f = append(f, "WriteOnly: true")
	}
	return strings.Join(f, ", ")
}

func fields(parts ...string) string {
	var out []string
	for _, p := range parts {
		if p != "" {
			out = append(out, p)
		}
	}
	return strings.Join(out, ",\n")
}

// attribute returns the Go type of the model field and the schema
// expression of an attribute.
func (g *generator) attribute(a *Attribute, path, base string) (string, string, error) {
	if a.NestedType != nil {
		name, attrs, _, err := g.object(a.NestedType.Attributes, nil, path, base)
		if err != nil {
			return "", "", err
		}
		if attrs == "" {
			attrs = "map[string]rsschema.Attribute{}"
		}
		switch a.NestedType.NestingMode {
		case "single":
			return "*" + name, fmt.Sprintf("rsschema.SingleNestedAttribute{\n%s,\n}", fields("Attributes: "+attrs, flags(a))), nil
		case "list", "set", "map":
			kind := map[string]string{"list": "List", "set": "Set", "map": "Map"}[a.NestedType.NestingMode]
			goType := "[]*" + name
			if kind == "Map" {
				goType = "map[string]*" + name
			}
			return goType, fmt.Sprintf("rsschema.%sNestedAttribute{\n%s,\n}", kind,
				fields("NestedObject: rsschema.NestedAttributeObject{\nAttributes: "+attrs+",\n}", flags(a))), nil
		}
		return "", "", fmt.Errorf("unsupported nesting mode %q", a.NestedType.NestingMode)
	}
	t, err := parseType(a.Type)
	if err != nil {
		return "", "", err
	}
	goType, _, err := g.value(t, path, base)
	if err != nil {
		return "", "", err
	}
	var expr string
	switch t.Kind {
	case "string", "bool", "dynamic", "number":
		expr = fmt.Sprintf("rsschema.%sAttribute{%s}", g.primName(t.Kind, path), flags(a))
	case "list", "set", "map":
		_, elem, _ := g.value(t.Elem, path, "")
		kind := map[string]string{"list": "List", "set": "Set", "map": "Map"}[t.Kind]
		expr = fmt.Sprintf("rsschema.%sAttribute{\n%s,\n}", kind, fields("ElementType: "+elem, flags(a)))
	case "object":
		expr = fmt.Sprintf("rsschema.ObjectAttribute{\n%s,\n}", fields("AttributeTypes: "+g.attrTypes(t, path), flags(a)))
	}
	return goType, expr, nil
}

// block returns the Go type of the model field and the schema expression of
// a nested block.
func (g *generator) block(nb *NestedBlock, path, base string) (string, string, error) {
	blk := nb.Block
	if blk == nil {
		blk = &Block{}
	}
	name, attrs, blocks, err := g.object(blk.Attributes, blk.BlockTypes, path, base)
	if err != nil {
		return "", "", err
	}
	if attrs != "" {
		attrs = "Attributes: " + attrs
	}
	if blocks != "" {
		blocks = "Blocks: " + blocks
	}
	body := fields(attrs, blocks)
	if body != "" {
		body += ","
	}
	switch nb.NestingMode {
	case "single", "group":
		return "*" + name, fmt.Sprintf("rsschema.SingleNestedBlock{\n%s\n}", body), nil
	case "list", "set":
		kind := map[string]string{"list": "List", "set": "Set"}[nb.NestingMode]
		return "[]*" + name, fmt.Sprintf("rsschema.%sNestedBlock{\nNestedObject: rsschema.NestedBlockObject{\n%s\n},\n}", kind, body), nil
	}
	return "", "", fmt.Errorf("unsupported block nesting mode %q", nb.NestingMode)
}

// primName returns the framework name of a primitive type: String, Bool,
// Dynamic, Number, Int64 or Float64.
func (g *generator) primName(kind, path string) string {
	switch kind {
	case "string":
		return "String"
	case "bool":
		return "Bool"
	case "dynamic":
		return "Dynamic"
	}
	n := g.o.Number
	if k, ok := g.o.Types[path]; ok {
		g.used[path] = true
		n = k
	}
	switch n {
	case NumberInt64:
		return "Int64"
	case NumberFloat64:
		return "Float64"
	}
	return "Number"
}

// value returns the Go type of a model field holding a value of type t and
// the Go expression of its attr.Type. base names the models of object
// values; with an empty base, no model is generated (types only).
func (g *generator) value(t *ctyType, path, base string) (string, string, error) {
	g.imports[fwTypes] = true
	switch t.Kind {
	case "string", "bool", "dynamic", "number":
		n := g.primName(t.Kind, path)
		return "types." + n, "types." + n + "Type", nil
	case "list", "set", "map":
		elemGo, elemType, err := g.value(t.Elem, path, base)
		if err != nil {
			return "", "", err
		}
		kind := map[string]string{"list": "List", "set": "Set", "map": "Map"}[t.Kind]
		goType := "[]" + elemGo
		if t.Kind == "map" {
			goType = "map[string]" + elemGo
		}
		return goType, fmt.Sprintf("types.%sType{ElemType: %s}", kind, elemType), nil
	case "object":
		types := "types.ObjectType{AttrTypes: " + g.attrTypes(t, path) + "}"
		if base == "" {
			return "", types, nil
		}
		s := g.newStruct(base, path)
		for _, k := range sortedKeys(t.Attrs) {
			goType, _, err := g.value(t.Attrs[k], join(path, k), base+gen.GoName(k))
			if err != nil {
				return "", "", err
			}
			s.fields = append(s.fields, fmt.Sprintf("%s %s `tfsdk:%q`", gen.GoName(k), goType, k))
		}
		return "*" + s.name, types, nil
	case "tuple":
		return "", "", fmt.Errorf("tuple types are not supported by the Plugin Framework")
	}
	return "", "", fmt.Errorf("unknown type %q", t.Kind)
}

// attrTypes returns the map[string]attr.Type expression of an object type.
func (g *generator) attrTypes(t *ctyType, path string) string {
	g.needAttr = true
	g.imports[fwTypes] = true
	var b strings.Builder
	b.WriteString("map[string]attr.Type{\n")
	for _, k := range sortedKeys(t.Attrs) {
		_, typ, _ := g.value(t.Attrs[k], join(path, k), "")
		fmt.Fprintf(&b, "%q: %s,\n", k, typ)
	}
	b.WriteString("}")
	return b.String()
}
