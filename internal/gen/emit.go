package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
)

// SchemaKind selects the Terraform schemas to generate.
type SchemaKind string

const (
	SchemaNone       SchemaKind = "none"
	SchemaDataSource SchemaKind = "datasource"
	SchemaResource   SchemaKind = "resource"
	SchemaBoth       SchemaKind = "both"
)

// EmitOptions configures Emit.
type EmitOptions struct {
	Package  string
	SpecName string // shown in the generated header
	Schema   SchemaKind
}

const (
	fwAttr     = "github.com/hashicorp/terraform-plugin-framework/attr"
	fwDiag     = "github.com/hashicorp/terraform-plugin-framework/diag"
	fwTypes    = "github.com/hashicorp/terraform-plugin-framework/types"
	fwDSSchema = "github.com/hashicorp/terraform-plugin-framework/datasource/schema"
	fwRSSchema = "github.com/hashicorp/terraform-plugin-framework/resource/schema"
)

var importAliases = map[string]string{fwDSSchema: "dsschema", fwRSSchema: "rsschema"}

type emitter struct {
	ep      *Endpoint
	buf     bytes.Buffer
	imports map[string]bool
}

func (e *emitter) p(format string, args ...any) {
	fmt.Fprintf(&e.buf, format, args...)
	e.buf.WriteByte('\n')
}

func (e *emitter) use(path string) { e.imports[path] = true }

// Emit renders the Go file for an endpoint.
func Emit(ep *Endpoint, o EmitOptions) ([]byte, error) {
	if o.Package == "" {
		o.Package = "provider"
	}
	if o.Schema == "" {
		o.Schema = SchemaDataSource
	}
	e := &emitter{ep: ep, imports: map[string]bool{}}
	e.use("context")
	e.use("encoding/json")
	e.use("fmt")
	e.use(fwDiag)
	e.use(fwTypes)

	for _, obj := range ep.Objects {
		e.apiType(obj)
	}
	for _, obj := range ep.Objects {
		e.modelType(obj)
	}
	switch o.Schema {
	case SchemaDataSource:
		e.schemas(fwDSSchema, "DataSource")
	case SchemaResource:
		e.schemas(fwRSSchema, "Resource")
	case SchemaBoth:
		e.schemas(fwDSSchema, "DataSource")
		e.schemas(fwRSSchema, "Resource")
	case SchemaNone:
	default:
		return nil, fmt.Errorf("unknown schema kind %q", o.Schema)
	}
	e.decode()
	e.fromAPI()
	for _, obj := range ep.Objects[1:] {
		e.objectFromAPI(obj)
	}
	e.requestHelpers()

	var out bytes.Buffer
	source := ""
	if o.SpecName != "" {
		source = " from " + o.SpecName
	}
	fmt.Fprintf(&out, "// Code generated by tfmodelgen%s (%s %s). DO NOT EDIT.\n\n", source, ep.Method, ep.Path)
	fmt.Fprintf(&out, "package %s\n\n", o.Package)
	out.WriteString(e.importBlock())
	out.Write(e.buf.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("formatting generated code: %w", err)
	}
	return formatted, nil
}

func (e *emitter) importBlock() string {
	var std, ext []string
	for path := range e.imports {
		line := strconv.Quote(path)
		if alias, ok := importAliases[path]; ok {
			line = alias + " " + line
		}
		if strings.Contains(path, ".") {
			ext = append(ext, line)
		} else {
			std = append(std, line)
		}
	}
	sort.Strings(std)
	sort.Strings(ext)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, l := range std {
		b.WriteString("\t" + l + "\n")
	}
	if len(std) > 0 && len(ext) > 0 {
		b.WriteString("\n")
	}
	for _, l := range ext {
		b.WriteString("\t" + l + "\n")
	}
	b.WriteString(")\n\n")
	return b.String()
}

// ---------------------------------------------------------------------------
// Types

func (e *emitter) root() *ObjectType { return e.ep.Objects[0] }

func (e *emitter) endpoint() string { return e.ep.Method + " " + e.ep.Path }

// goAPIType is the Go type of a value in the API structs. Scalars are
// pointers at field level so that absent and null values stay distinct from
// zero values.
func (e *emitter) goAPIType(n *Node, field bool) string {
	ptr := field || n.Nullable
	switch n.Kind {
	case KString:
		return star(ptr) + "string"
	case KInt:
		return star(ptr) + "int64"
	case KFloat:
		return star(ptr) + "float64"
	case KBool:
		return star(ptr) + "bool"
	case KJSON:
		return "json.RawMessage"
	case KObject:
		return "*" + n.Object.Name + "API"
	case KList:
		return "[]" + e.goAPIType(n.Elem, false)
	case KMap:
		return "map[string]" + e.goAPIType(n.Elem, false)
	}
	panic("unknown kind")
}

func star(ptr bool) string {
	if ptr {
		return "*"
	}
	return ""
}

func (e *emitter) apiType(obj *ObjectType) {
	if obj == e.root() && e.ep.Wrapped {
		f := obj.Fields[len(obj.Fields)-1]
		e.p("// %sAPI is the body of the %s response (%s).", obj.Name, e.endpoint(), e.ep.Status)
		e.p("type %sAPI %s", obj.Name, e.goAPIType(f.Node, false))
		e.p("")
		return
	}
	if obj == e.root() {
		e.p("// %sAPI is the body of the %s response (%s).", obj.Name, e.endpoint(), e.ep.Status)
	} else {
		e.p("// %sAPI is a nested object of the %s response.", obj.Name, e.endpoint())
	}
	e.p("type %sAPI struct {", obj.Name)
	for _, f := range obj.Fields {
		if f.FromResponse {
			e.p("%s %s `json:\"%s\"`", f.GoName, e.goAPIType(f.Node, true), f.JSONName)
		}
	}
	e.p("}")
	e.p("")
}

func modelGoType(n *Node) string {
	switch n.Kind {
	case KString, KJSON:
		return "types.String"
	case KInt:
		return "types.Int64"
	case KFloat:
		return "types.Float64"
	case KBool:
		return "types.Bool"
	case KObject:
		return "types.Object"
	case KList:
		return "types.List"
	case KMap:
		return "types.Map"
	}
	panic("unknown kind")
}

func (e *emitter) attrType(n *Node) string {
	switch n.Kind {
	case KString, KJSON:
		return "types.StringType"
	case KInt:
		return "types.Int64Type"
	case KFloat:
		return "types.Float64Type"
	case KBool:
		return "types.BoolType"
	case KObject:
		return "types.ObjectType{AttrTypes: " + n.Object.Name + "Model{}.AttrTypes()}"
	case KList:
		return "types.ListType{ElemType: " + e.attrType(n.Elem) + "}"
	case KMap:
		return "types.MapType{ElemType: " + e.attrType(n.Elem) + "}"
	}
	panic("unknown kind")
}

func (e *emitter) modelType(obj *ObjectType) {
	if obj == e.root() {
		e.p("// %sModel is the Terraform model of the %s response.", obj.Name, e.endpoint())
	} else {
		e.p("// %sModel is the Terraform model of %sAPI.", obj.Name, obj.Name)
	}
	e.p("type %sModel struct {", obj.Name)
	for _, f := range obj.Fields {
		e.p("%s %s `tfsdk:%q`", f.GoName, modelGoType(f.Node), f.TFName)
	}
	e.p("}")
	e.p("")
	if obj == e.root() {
		return
	}
	e.use(fwAttr)
	e.p("// AttrTypes returns the attribute types of %sModel.", obj.Name)
	e.p("func (%sModel) AttrTypes() map[string]attr.Type {", obj.Name)
	e.p("return map[string]attr.Type{")
	for _, f := range obj.Fields {
		e.p("%q: %s,", f.TFName, e.attrType(f.Node))
	}
	e.p("}")
	e.p("}")
	e.p("")
}

// ---------------------------------------------------------------------------
// Schemas

func (e *emitter) schemas(pkgPath, kind string) {
	e.use(pkgPath)
	pkg := importAliases[pkgPath]
	root := e.root()
	label := map[string]string{"DataSource": "data source", "Resource": "resource"}[kind]

	e.p("// %s%sSchema returns the %s schema of the %s response.", root.Name, kind, label, e.endpoint())
	e.p("func %s%sSchema() %s.Schema {", root.Name, kind, pkg)
	e.p("return %s.Schema{", pkg)
	if root.Desc != "" {
		e.p("Description: %s,", strconv.Quote(root.Desc))
	}
	e.p("Attributes: %s%sAttributes(),", root.Name, kind)
	e.p("}")
	e.p("}")
	e.p("")

	for i, obj := range e.ep.Objects {
		fn := e.attrsFunc(obj, kind)
		if i == 0 {
			e.p("// %s returns the attributes of %sModel, to embed them in another schema.", fn, obj.Name)
		}
		e.p("func %s() map[string]%s.Attribute {", fn, pkg)
		e.p("return map[string]%s.Attribute{", pkg)
		for _, f := range obj.Fields {
			e.p("%q: %s,", f.TFName, e.attribute(pkg, kind, f))
		}
		e.p("}")
		e.p("}")
		e.p("")
	}
}

func (e *emitter) attrsFunc(obj *ObjectType, kind string) string {
	if obj == e.root() {
		return obj.Name + kind + "Attributes"
	}
	return lowerFirst(obj.Name) + kind + "Attributes"
}

func (e *emitter) attribute(pkg, kind string, f *Field) string {
	var props []string
	switch {
	case f.Param != nil && f.Param.In == "path":
		props = append(props, "Required: true")
	case f.Param != nil && f.Param.Required && !f.FromResponse:
		props = append(props, "Required: true")
	case f.Param != nil:
		props = append(props, "Optional: true")
		if f.FromResponse {
			props = append(props, "Computed: true")
		}
	default:
		props = append(props, "Computed: true")
	}
	if f.Desc != "" {
		props = append(props, "Description: "+strconv.Quote(f.Desc))
	}
	if f.Sensitive {
		props = append(props, "Sensitive: true")
	}
	if f.Deprecated {
		props = append(props, `DeprecationMessage: "Deprecated by the API."`)
	}

	n := f.Node
	typ := ""
	switch n.Kind {
	case KString, KJSON:
		typ = "StringAttribute"
	case KInt:
		typ = "Int64Attribute"
	case KFloat:
		typ = "Float64Attribute"
	case KBool:
		typ = "BoolAttribute"
	case KObject:
		typ = "SingleNestedAttribute"
		props = append(props, "Attributes: "+e.attrsFunc(n.Object, kind)+"()")
	case KList, KMap:
		prefix := "List"
		if n.Kind == KMap {
			prefix = "Map"
		}
		if n.Elem.Kind == KObject {
			typ = prefix + "NestedAttribute"
			props = append(props, fmt.Sprintf("NestedObject: %s.NestedAttributeObject{Attributes: %s()}",
				pkg, e.attrsFunc(n.Elem.Object, kind)))
		} else {
			typ = prefix + "Attribute"
			props = append(props, "ElementType: "+e.attrType(n.Elem))
		}
	}
	return pkg + "." + typ + "{\n" + strings.Join(props, ",\n") + ",\n}"
}

// ---------------------------------------------------------------------------
// Conversion helpers

func (e *emitter) decode() {
	root := e.root()
	e.p("// Decode%sAPI decodes the body of a %s response.", root.Name, e.endpoint())
	e.p("func Decode%sAPI(body []byte) (*%sAPI, error) {", root.Name, root.Name)
	e.p("var out %sAPI", root.Name)
	e.p("if err := json.Unmarshal(body, &out); err != nil {")
	e.p("return nil, fmt.Errorf(%q, err)", "decoding "+e.endpoint()+" response: %w")
	e.p("}")
	e.p("return &out, nil")
	e.p("}")
	e.p("")
}

func (e *emitter) fromAPI() {
	root := e.root()
	e.p("// FromAPI sets the model from a %s response. Attributes that only", e.endpoint())
	e.p("// carry request parameters are left untouched.")
	e.p("func (m *%sModel) FromAPI(ctx context.Context, in *%sAPI) diag.Diagnostics {", root.Name, root.Name)
	e.p("var diags diag.Diagnostics")
	e.p("if in == nil {")
	e.p("diags.AddError(%q, %q)", "Empty API response", e.endpoint()+" returned no data.")
	e.p("return diags")
	e.p("}")
	for _, f := range root.Fields {
		if !f.FromResponse {
			continue
		}
		if e.ep.Wrapped {
			e.convert("m."+f.GoName, "(*in)", f.Node, false, 0)
		} else {
			e.convert("m."+f.GoName, "in."+f.GoName, f.Node, true, 0)
		}
	}
	e.p("return diags")
	e.p("}")
	e.p("")
}

func (e *emitter) convFunc(obj *ObjectType) string { return lowerFirst(obj.Name) + "FromAPI" }

func (e *emitter) objectFromAPI(obj *ObjectType) {
	e.use(fwAttr)
	e.p("// %s converts a %sAPI into an object value; nil gives a null object.", e.convFunc(obj), obj.Name)
	e.p("func %s(ctx context.Context, in *%sAPI) (types.Object, diag.Diagnostics) {", e.convFunc(obj), obj.Name)
	e.p("attrTypes := %sModel{}.AttrTypes()", obj.Name)
	e.p("if in == nil {")
	e.p("return types.ObjectNull(attrTypes), nil")
	e.p("}")
	if len(obj.Fields) == 0 {
		e.p("return types.ObjectValueMust(attrTypes, map[string]attr.Value{}), nil")
		e.p("}")
		e.p("")
		return
	}
	e.p("var diags diag.Diagnostics")
	e.p("var m %sModel", obj.Name)
	for _, f := range obj.Fields {
		e.convert("m."+f.GoName, "in."+f.GoName, f.Node, true, 0)
	}
	e.p("v, d := types.ObjectValue(attrTypes, map[string]attr.Value{")
	for _, f := range obj.Fields {
		e.p("%q: m.%s,", f.TFName, f.GoName)
	}
	e.p("})")
	e.p("diags.Append(d...)")
	e.p("return v, diags")
	e.p("}")
	e.p("")
}

// convert writes code assigning the Terraform value of src to dst. ptr tells
// whether a scalar src is a pointer.
func (e *emitter) convert(dst, src string, n *Node, ptr bool, depth int) {
	scalar := func(fn string) {
		if ptr {
			e.p("%s = types.%sPointerValue(%s)", dst, fn, src)
		} else {
			e.p("%s = types.%sValue(%s)", dst, fn, src)
		}
	}
	switch n.Kind {
	case KString:
		scalar("String")
	case KInt:
		scalar("Int64")
	case KFloat:
		scalar("Float64")
	case KBool:
		scalar("Bool")
	case KJSON:
		e.p("if len(%s) == 0 || string(%s) == \"null\" {", src, src)
		e.p("%s = types.StringNull()", dst)
		e.p("} else {")
		e.p("%s = types.StringValue(string(%s))", dst, src)
		e.p("}")
	case KObject:
		e.p("{")
		e.p("v%d, d%d := %s(ctx, %s)", depth, depth, e.convFunc(n.Object), src)
		e.p("diags.Append(d%d...)", depth)
		e.p("%s = v%d", dst, depth)
		e.p("}")
	case KList, KMap:
		e.use(fwAttr)
		kind := "List"
		if n.Kind == KMap {
			kind = "Map"
		}
		elemType := e.attrType(n.Elem)
		e.p("if %s == nil {", src)
		e.p("%s = types.%sNull(%s)", dst, kind, elemType)
		e.p("} else {")
		if n.Kind == KList {
			e.p("elems%d := make([]attr.Value, 0, len(%s))", depth, src)
			e.p("for _, item%d := range %s {", depth, src)
		} else {
			e.p("elems%d := make(map[string]attr.Value, len(%s))", depth, src)
			e.p("for key%d, item%d := range %s {", depth, depth, src)
		}
		e.p("var elem%d attr.Value", depth)
		e.convert(fmt.Sprintf("elem%d", depth), fmt.Sprintf("item%d", depth), n.Elem, n.Elem.Nullable, depth+1)
		if n.Kind == KList {
			e.p("elems%d = append(elems%d, elem%d)", depth, depth, depth)
		} else {
			e.p("elems%d[key%d] = elem%d", depth, depth, depth)
		}
		e.p("}")
		e.p("v%d, d%d := types.%sValue(%s, elems%d)", depth, depth, kind, elemType, depth)
		e.p("diags.Append(d%d...)", depth)
		e.p("%s = v%d", dst, depth)
		e.p("}")
	}
}

// requestHelpers writes APIPath and APIQuery for operations with parameters.
func (e *emitter) requestHelpers() {
	var path, query []*Param
	for _, p := range e.ep.Params {
		if p.In == "path" {
			path = append(path, p)
		} else {
			query = append(query, p)
		}
	}
	root := e.root()
	if len(path) > 0 {
		e.use("net/url")
		e.use("strings")
		e.p("// APIPath returns the request path of %s built from the model.", e.endpoint())
		e.p("func (m *%sModel) APIPath() (string, error) {", root.Name)
		e.p("p := %q", e.ep.Path)
		for _, p := range path {
			field := "m." + p.Field.GoName
			e.p("if %s.IsNull() || %s.IsUnknown() {", field, field)
			e.use("errors")
			e.p("return \"\", errors.New(%q)", fmt.Sprintf("attribute %q is required to build the request path", p.Field.TFName))
			e.p("}")
			e.p("p = strings.ReplaceAll(p, %q, url.PathEscape(%s))", "{"+p.Name+"}", e.valueString(field, p.Field.Node))
		}
		e.p("return p, nil")
		e.p("}")
		e.p("")
	}
	if len(query) > 0 {
		e.use("net/url")
		e.p("// APIQuery returns the query parameters of %s set in the model.", e.endpoint())
		e.p("func (m *%sModel) APIQuery() url.Values {", root.Name)
		e.p("q := url.Values{}")
		for _, p := range query {
			field := "m." + p.Field.GoName
			e.p("if !%s.IsNull() && !%s.IsUnknown() {", field, field)
			e.p("q.Set(%q, %s)", p.Name, e.valueString(field, p.Field.Node))
			e.p("}")
		}
		e.p("return q")
		e.p("}")
		e.p("")
	}
}

func (e *emitter) valueString(field string, n *Node) string {
	switch n.Kind {
	case KInt:
		e.use("strconv")
		return "strconv.FormatInt(" + field + ".ValueInt64(), 10)"
	case KFloat:
		e.use("strconv")
		return "strconv.FormatFloat(" + field + ".ValueFloat64(), 'f', -1, 64)"
	case KBool:
		e.use("strconv")
		return "strconv.FormatBool(" + field + ".ValueBool())"
	default:
		return field + ".ValueString()"
	}
}
