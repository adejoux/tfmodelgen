func modelGoType(n *Node) string {
	switch n.Kind {
	case KString, KJSON:
		return "types.String"
	case KInt:
		return "types.Int64"
	case KFloat:
		return "types.Float64"
	case KBool:
		return "types.Bool"
	case KObject:
		return "types.Object"
	case KList:
		return "types.List"
	case KMap:
		return "types.Map"
	}
	panic("unknown kind")
}

func (e *emitter) attrType(n *Node) string {
	switch n.Kind {
	case KString, KJSON:
		return "types.StringType"
	case KInt:
		return "types.Int64Type"
	case KFloat:
		return "types.Float64Type"
	case KBool:
		return "types.BoolType"
	case KObject:
		return "types.ObjectType{AttrTypes: " + n.Object.Name + "Model{}.AttrTypes()}"
	case KList:
		return "types.ListType{ElemType: " + e.attrType(n.Elem) + "}"
	case KMap:
		return "types.MapType{ElemType: " + e.attrType(n.Elem) + "}"
	}
	panic("unknown kind")
}

func (e *emitter) modelType(obj *ObjectType) {
	if obj == e.root() {
		e.p("// %sModel holds the Terraform attributes read from the %s response.", obj.Name, e.endpoint())
		e.p("// Embed it by value in a resource model to store these attributes; FromAPI")
		e.p("// is then promoted to that model. %sDataSourceModel embeds it too.", obj.Name)
	} else {
		e.p("// %sModel is the Terraform model of %sAPI.", obj.Name, obj.Name)
	}
	e.p("type %sModel struct {", obj.Name)
	for _, f := range e.exposed(obj) {
		e.p("%s %s `tfsdk:%q`", f.GoName, modelGoType(f.Node), f.TFName)
	}
	e.p("}")
	e.p("")
	if obj == e.root() {
		return
	}
	e.use(fwAttr)
	e.p("// AttrTypes returns the attribute types of %sModel.", obj.Name)
	e.p("func (%sModel) AttrTypes() map[string]attr.Type {", obj.Name)
	e.p("return map[string]attr.Type{")
	for _, f := range obj.Fields {
		e.p("%q: %s,", f.TFName, e.attrType(f.Node))
	}
	e.p("}")
	e.p("}")
	e.p("")
	e.p("// ObjectType returns the Terraform type of %sModel, for instance the", obj.Name)
	e.p("// element type of a list built with types.ListValueFrom.")
	e.p("func (m %sModel) ObjectType() types.ObjectType {", obj.Name)
	e.p("return types.ObjectType{AttrTypes: m.AttrTypes()}")
	e.p("}")
	e.p("")
}

func (e *emitter) schemas(pkgPath, kind string) {
	e.use(pkgPath)
	pkg := importAliases[pkgPath]
	root := e.root()

	if kind == "DataSource" {
		e.p("// %sDataSourceSchema returns the schema of a data source reading %s.", root.Name, e.endpoint())
		e.p("func %sDataSourceSchema() %s.Schema {", root.Name, pkg)
		e.p("return %s.Schema{", pkg)
		if root.Desc != "" {
			e.p("Description: %s,", strconv.Quote(root.Desc))
		}
		e.p("Attributes: %sDataSourceAttributes(),", root.Name)
		e.p("}")
		e.p("}")
		e.p("")
		e.p("// %sDataSourceAttributes returns the attributes of %sDataSourceModel: the", root.Name, root.Name)
		e.p("// request parameters as arguments, and the computed response attributes.")
	} else {
		e.p("// %sResourceAttributes returns the attributes of %sModel, all computed.", root.Name, root.Name)
		e.p("// Merge them into the schema of the resource that embeds %sModel.", root.Name)
	}
	for _, obj := range e.models() {
		e.p("func %s() map[string]%s.Attribute {", e.attrsFunc(obj, kind), pkg)
		e.p("return map[string]%s.Attribute{", pkg)
		if obj == root && kind == "DataSource" {
			for _, p := range e.ep.Params {
				if p.Field == nil {
					e.p("%q: %s,", p.TFName, e.paramAttribute(pkg, p))
				}
			}
		}
		for _, f := range e.exposed(obj) {
			var p *Param
			if obj == root && kind == "DataSource" {
				p = e.paramOf[f]
			}
			e.p("%q: %s,", f.TFName, e.attribute(pkg, kind, f, p))
		}
		e.p("}")
		e.p("}")
		e.p("")
	}
}

// argumentProps returns the schema properties of a data source argument.
func argumentProps(p *Param, computed bool) []string {
	switch {
	case p.Required:
		return []string{"Required: true"}
	case computed:
		return []string{"Optional: true", "Computed: true"}
	default:
		return []string{"Optional: true"}
	}
}

func scalarAttribute(k Kind) string {
	return map[Kind]string{KString: "StringAttribute", KJSON: "StringAttribute", KInt: "Int64Attribute",
		KFloat: "Float64Attribute", KBool: "BoolAttribute"}[k]
}

func (e *emitter) paramAttribute(pkg string, p *Param) string {
	props := argumentProps(p, false)
	if p.Desc != "" {
		props = append(props, "Description: "+strconv.Quote(p.Desc))
	}
	if p.Deprecated {
		props = append(props, `DeprecationMessage: "Deprecated by the API."`)
	}
	return pkg + "." + scalarAttribute(p.Node.Kind) + "{\n" + strings.Join(props, ",\n") + ",\n}"
}

func (e *emitter) attrsFunc(obj *ObjectType, kind string) string {
	if obj == e.root() {
		return obj.Name + kind + "Attributes"
	}
	return lowerFirst(obj.Name) + kind + "Attributes"
}

// attribute returns the schema of a response attribute. p is the data
// source argument it also carries, if any.
func (e *emitter) attribute(pkg, kind string, f *Field, p *Param) string {
	props := []string{"Computed: true"}
	desc := f.Desc
	if p != nil {
		props = argumentProps(p, true)
		desc = firstNonEmpty(f.Desc, p.Desc)
	}
	if desc != "" {
		props = append(props, "Description: "+strconv.Quote(desc))
	}
	if f.Sensitive {
		props = append(props, "Sensitive: true")
	}
	if f.Deprecated {
		props = append(props, `DeprecationMessage: "Deprecated by the API."`)
	}

	n := f.Node
	typ := ""
	switch n.Kind {
	case KString, KJSON, KInt, KFloat, KBool:
		typ = scalarAttribute(n.Kind)
	case KObject:
		typ = "SingleNestedAttribute"
		props = append(props, "Attributes: "+e.attrsFunc(n.Object, kind)+"()")
	case KList, KMap:
		prefix := "List"
		if n.Kind == KMap {
			prefix = "Map"
		}
		if n.Elem.Kind == KObject {
			typ = prefix + "NestedAttribute"
			props = append(props, fmt.Sprintf("NestedObject: %s.NestedAttributeObject{Attributes: %s()}",
				pkg, e.attrsFunc(n.Elem.Object, kind)))
		} else {
			typ = prefix + "Attribute"
			props = append(props, "ElementType: "+e.attrType(n.Elem))
		}
	}
	return pkg + "." + typ + "{\n" + strings.Join(props, ",\n") + ",\n}"
}

func (e *emitter) fromAPI() {
	root := e.root()
	e.p("// FromAPI sets the attributes of the model from a %s response.", e.endpoint())
	e.p("func (m *%sModel) FromAPI(ctx context.Context, in *%sAPI) diag.Diagnostics {", root.Name, root.Name)
	e.p("var diags diag.Diagnostics")
	e.p("if in == nil {")
	e.p("diags.AddError(%q, %q)", "Empty API response", e.endpoint()+" returned no data.")
	e.p("return diags")
	e.p("}")
	for _, f := range e.exposed(root) {
		if e.ep.Wrapped {
			e.convert("m."+f.GoName, "(*in)", f.Node, false, 0)
		} else {
			e.convert("m."+f.GoName, "in."+f.GoName, f.Node, true, 0)
		}
	}
	e.p("return diags")
	e.p("}")
	e.p("")
}

func (e *emitter) convFunc(obj *ObjectType) string { return lowerFirst(obj.Name) + "FromAPI" }

func (e *emitter) objectFromAPI(obj *ObjectType) {
	e.use(fwAttr)
	n := obj.Name

	e.p("// FromAPI sets the model from a %sAPI; a nil value gives null attributes.", n)
	e.p("func (m *%sModel) FromAPI(ctx context.Context, in *%sAPI) diag.Diagnostics {", n, n)
	e.p("var diags diag.Diagnostics")
	if len(obj.Fields) > 0 {
		e.p("if in == nil {")
		e.p("in = &%sAPI{}", n)
		e.p("}")
	}
	for _, f := range obj.Fields {
		e.convert("m."+f.GoName, "in."+f.GoName, f.Node, true, 0)
	}
	e.p("return diags")
	e.p("}")
	e.p("")

	e.p("// ObjectValue returns the model as an object value, for instance to append")
	e.p("// it to the elements of a list.")
	e.p("func (m %sModel) ObjectValue() (types.Object, diag.Diagnostics) {", n)
	e.p("return types.ObjectValue(m.AttrTypes(), map[string]attr.Value{")
	for _, f := range obj.Fields {
		e.p("%q: m.%s,", f.TFName, f.GoName)
	}
	e.p("})")
	e.p("}")
	e.p("")

	e.p("// %s converts a %sAPI into an object value; nil gives a null object.", e.convFunc(obj), n)
	e.p("func %s(ctx context.Context, in *%sAPI) (types.Object, diag.Diagnostics) {", e.convFunc(obj), n)
	e.p("if in == nil {")
	e.p("return types.ObjectNull(%sModel{}.AttrTypes()), nil", n)
	e.p("}")
	e.p("var m %sModel", n)
	e.p("diags := m.FromAPI(ctx, in)")
	e.p("v, d := m.ObjectValue()")
	e.p("diags.Append(d...)")
	e.p("return v, diags")
	e.p("}")
	e.p("")
}

// convert writes code assigning the Terraform value of src to dst. ptr tells
// whether a scalar src is a pointer.
func (e *emitter) convert(dst, src string, n *Node, ptr bool, depth int) {
	scalar := func(fn string) {
		if ptr {
			e.p("%s = types.%sPointerValue(%s)", dst, fn, src)
		} else {
			e.p("%s = types.%sValue(%s)", dst, fn, src)
		}
	}
	switch n.Kind {
	case KString:
		scalar("String")
	case KInt:
		scalar("Int64")
	case KFloat:
		scalar("Float64")
	case KBool:
		scalar("Bool")
	case KJSON:
		e.p("if len(%s) == 0 || string(%s) == \"null\" {", src, src)
		e.p("%s = types.StringNull()", dst)
		e.p("} else {")
		e.p("%s = types.StringValue(string(%s))", dst, src)
		e.p("}")
	case KObject:
		e.p("{")
		e.p("v%d, d%d := %s(ctx, %s)", depth, depth, e.convFunc(n.Object), src)
		e.p("diags.Append(d%d...)", depth)
		e.p("%s = v%d", dst, depth)
		e.p("}")
	case KList, KMap:
		e.use(fwAttr)
		kind := "List"
		if n.Kind == KMap {
			kind = "Map"
		}
		elemType := e.attrType(n.Elem)
		e.p("if %s == nil {", src)
		e.p("%s = types.%sNull(%s)", dst, kind, elemType)
		e.p("} else {")
		if n.Kind == KList {
			e.p("elems%d := make([]attr.Value, 0, len(%s))", depth, src)
			e.p("for _, item%d := range %s {", depth, src)
		} else {
			e.p("elems%d := make(map[string]attr.Value, len(%s))", depth, src)
			e.p("for key%d, item%d := range %s {", depth, depth, src)
		}
		e.p("var elem%d attr.Value", depth)
		e.convert(fmt.Sprintf("elem%d", depth), fmt.Sprintf("item%d", depth), n.Elem, n.Elem.Nullable, depth+1)
		if n.Kind == KList {
			e.p("elems%d = append(elems%d, elem%d)", depth, depth, depth)
		} else {
			e.p("elems%d[key%d] = elem%d", depth, depth, depth)
		}
		e.p("}")
		e.p("v%d, d%d := types.%sValue(%s, elems%d)", depth, depth, kind, elemType, depth)
		e.p("diags.Append(d%d...)", depth)
		e.p("%s = v%d", dst, depth)
		e.p("}")
	}
}

// dataSourceModel writes the model of a data source: the parameters that are
// not response attributes, and the embedded response model.
func (e *emitter) dataSourceModel() {
	root := e.root()
	e.p("// %sDataSourceModel is the model of a data source reading %s: its", root.Name, e.endpoint())
	e.p("// arguments are the request parameters (see APIPath and APIQuery), its")
	e.p("// computed attributes come from %sModel.", root.Name)
	e.p("type %sDataSourceModel struct {", root.Name)
	for _, p := range e.ep.Params {
		if p.Field == nil {
			e.p("%s %s `tfsdk:%q`", p.ModelGoName, modelGoType(p.Node), p.TFName)
		}
	}
	e.p("%sModel", root.Name)
	e.p("}")
	e.p("")
}

func (e *emitter) argField(p *Param) string {
	if p.Field != nil {
		return "m." + p.Field.GoName
	}
	return "m." + p.ModelGoName
}

func valueMethod(k Kind) string {
	return map[Kind]string{KString: "ValueString", KInt: "ValueInt64", KFloat: "ValueFloat64", KBool: "ValueBool"}[k]
}

// dataSourceRequest writes FromAPI, APIPath and APIQuery on the data source
// model.
func (e *emitter) dataSourceRequest() {
	root := e.root()
	var bound []*Param
	for _, p := range e.ep.Params {
		if p.Field != nil {
			bound = append(bound, p)
		}
	}
	if len(bound) > 0 {
		e.p("// FromAPI sets the computed attributes from a %s response. Arguments", e.endpoint())
		e.p("// keep their configured values, as Terraform requires.")
		e.p("func (m *%sDataSourceModel) FromAPI(ctx context.Context, in *%sAPI) diag.Diagnostics {", root.Name, root.Name)
		for i, p := range bound {
			e.p("arg%d := %s", i, e.argField(p))
		}
		e.p("diags := m.%sModel.FromAPI(ctx, in)", root.Name)
		for i, p := range bound {
			e.p("%s = arg%d", e.argField(p), i)
		}
		e.p("return diags")
		e.p("}")
		e.p("")
	}
	var args []string
	var query []*Param
	e.p("// APIPath returns the request path of %s built from the data source arguments.", e.endpoint())
	e.p("func (m *%sDataSourceModel) APIPath() (string, error) {", root.Name)
	for _, p := range e.ep.Params {
		if p.In != "path" {
			query = append(query, p)
			continue
		}
		field := e.argField(p)
		e.use("errors")
		e.p("if %s.IsNull() || %s.IsUnknown() {", field, field)
		e.p("return \"\", errors.New(%q)", fmt.Sprintf("attribute %q is required to build the request path", p.TFName))
		e.p("}")
		args = append(args, field+"."+valueMethod(p.Node.Kind)+"()")
	}
	e.p("return %sPath(%s), nil", root.Name, strings.Join(args, ", "))
	e.p("}")
	e.p("")
	if len(query) == 0 {
		return
	}
	e.p("// APIQuery returns the query parameters of %s set in the data source arguments.", e.endpoint())
	e.p("func (m *%sDataSourceModel) APIQuery() url.Values {", root.Name)
	e.p("var q %sQuery", root.Name)
	for _, p := range query {
		field := e.argField(p)
		value := field + "." + valueMethod(p.Node.Kind) + "()"
		if p.Required {
			e.p("q.%s = %s", p.GoName, value)
			continue
		}
		e.p("if !%s.IsNull() && !%s.IsUnknown() {", field, field)
		e.p("v := %s", value)
		e.p("q.%s = &v", p.GoName)
		e.p("}")
	}
	e.p("return q.Values()")
	e.p("}")
	e.p("")
}
