package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
)

// SchemaKind selects the Terraform schemas to generate.
type SchemaKind string

const (
	SchemaNone       SchemaKind = "none"
	SchemaDataSource SchemaKind = "datasource"
	SchemaResource   SchemaKind = "resource"
	SchemaBoth       SchemaKind = "both"
)

// EmitOptions configures Emit.
type EmitOptions struct {
	Package  string
	SpecName string     // shown in the generated header
	Schema   SchemaKind // default SchemaDataSource
}

const (
	fwAttr     = "github.com/hashicorp/terraform-plugin-framework/attr"
	fwDiag     = "github.com/hashicorp/terraform-plugin-framework/diag"
	fwTypes    = "github.com/hashicorp/terraform-plugin-framework/types"
	fwDSSchema = "github.com/hashicorp/terraform-plugin-framework/datasource/schema"
	fwRSSchema = "github.com/hashicorp/terraform-plugin-framework/resource/schema"
)

var importAliases = map[string]string{fwDSSchema: "dsschema", fwRSSchema: "rsschema"}

type emitter struct {
	ep        *Endpoint
	buf       bytes.Buffer
	imports   map[string]bool
	reachable map[*ObjectType]bool // nested objects behind exposed attributes
	consts    map[string]bool
	paramOf   map[*Field]*Param // response attributes carrying a data source argument
}

func (e *emitter) p(format string, args ...any) {
	fmt.Fprintf(&e.buf, format, args...)
	e.buf.WriteByte('\n')
}

func (e *emitter) use(path string) { e.imports[path] = true }

// Emit renders the Go file for an endpoint.
func Emit(ep *Endpoint, o EmitOptions) ([]byte, error) {
	if o.Package == "" {
		o.Package = "provider"
	}
	if o.Schema == "" {
		o.Schema = SchemaDataSource
	}
	switch o.Schema {
	case SchemaNone, SchemaDataSource, SchemaResource, SchemaBoth:
	default:
		return nil, fmt.Errorf("unknown schema kind %q", o.Schema)
	}
	e := &emitter{ep: ep, imports: map[string]bool{}, consts: map[string]bool{}, paramOf: map[*Field]*Param{}}
	for _, p := range ep.Params {
		if p.Field != nil {
			e.paramOf[p.Field] = p
		}
	}
	e.findReachable()
	dataSource := o.Schema == SchemaDataSource || o.Schema == SchemaBoth
	resource := o.Schema == SchemaResource || o.Schema == SchemaBoth
	e.use("context")
	e.use("encoding/json")
	e.use("fmt")
	e.use(fwDiag)
	e.use(fwTypes)

	// Go side: API structs and request helpers.
	for _, obj := range ep.Objects {
		e.apiType(obj)
	}
	e.decode()
	e.requestHelpers()

	// Terraform side: models, schemas and conversions.
	for _, obj := range e.models() {
		e.modelType(obj)
	}
	if dataSource {
		e.dataSourceModel()
		e.schemas(fwDSSchema, "DataSource")
	}
	if resource {
		e.schemas(fwRSSchema, "Resource")
	}
	e.fromAPI()
	for _, obj := range e.models()[1:] {
		e.objectFromAPI(obj)
	}
	if dataSource {
		e.dataSourceRequest()
	}

	var out bytes.Buffer
	source := ""
	if o.SpecName != "" {
		source = " from " + o.SpecName
	}
	fmt.Fprintf(&out, "// Code generated by tfmodelgen%s (%s %s). DO NOT EDIT.\n\n", source, ep.Method, ep.Path)
	fmt.Fprintf(&out, "package %s\n\n", o.Package)
	out.WriteString(e.importBlock())
	out.Write(e.buf.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("formatting generated code: %w", err)
	}
	return formatted, nil
}

func (e *emitter) importBlock() string {
	var std, ext []string
	for path := range e.imports {
		line := strconv.Quote(path)
		if alias, ok := importAliases[path]; ok {
			line = alias + " " + line
		}
		if strings.Contains(path, ".") {
			ext = append(ext, line)
		} else {
			std = append(std, line)
		}
	}
	sort.Strings(std)
	sort.Strings(ext)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, l := range std {
		b.WriteString("\t" + l + "\n")
	}
	if len(std) > 0 && len(ext) > 0 {
		b.WriteString("\n")
	}
	for _, l := range ext {
		b.WriteString("\t" + l + "\n")
	}
	b.WriteString(")\n\n")
	return b.String()
}

func (e *emitter) root() *ObjectType { return e.ep.Objects[0] }

func (e *emitter) endpoint() string { return e.ep.Method + " " + e.ep.Path }

// exposed returns the fields of obj that are Terraform attributes.
func (e *emitter) exposed(obj *ObjectType) []*Field {
	var out []*Field
	for _, f := range obj.Fields {
		if f.Exposed || obj != e.root() {
			out = append(out, f)
		}
	}
	return out
}

func (e *emitter) findReachable() {
	e.reachable = map[*ObjectType]bool{}
	var walk func(n *Node)
	walk = func(n *Node) {
		switch n.Kind {
		case KObject:
			if e.reachable[n.Object] {
				return
			}
			e.reachable[n.Object] = true
			for _, f := range n.Object.Fields {
				walk(f.Node)
			}
		case KList, KMap:
			walk(n.Elem)
		}
	}
	for _, f := range e.exposed(e.root()) {
		walk(f.Node)
	}
}

// models returns the root and the nested objects that need a Terraform model.
func (e *emitter) models() []*ObjectType {
	out := []*ObjectType{e.root()}
	for _, obj := range e.ep.Objects[1:] {
		if e.reachable[obj] {
			out = append(out, obj)
		}
	}
	return out
}

